-- ==========================================
-- DATABASE: GESTION PHARMACEUTIQUE
-- ORACLE APEX VERSION
-- ==========================================

-- 1. FOURNISSEUR
CREATE TABLE Fournisseur (
    id_fournisseur NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_fournisseur VARCHAR2(150) NOT NULL,
    adresse VARCHAR2(255),
    telephone VARCHAR2(20),
    e_mail VARCHAR2(150)
);

-- 2. UTILISATEUR
CREATE TABLE Utilisateur (
    id_utilisateur NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_utilisateur VARCHAR2(150) NOT NULL,
    role_utilisateur VARCHAR2(50) NOT NULL,
    code_rfid VARCHAR2(100) UNIQUE
);

-- 3. MATIERE PREMIERE
CREATE TABLE Matiere_premiere (
    id_matiere NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_matiere VARCHAR2(150) NOT NULL,
    type_matiere VARCHAR2(100),
    stock_actuel NUMBER(10,2) DEFAULT 0,
    stock_minimal NUMBER(10,2) DEFAULT 0
);

-- 4. COMMANDE FOURNISSEUR
CREATE TABLE Commande_Fournisseur (
    id_commande NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_commande DATE NOT NULL,
    date_livraison DATE,
    id_matiere NUMBER NOT NULL,
    id_fournisseur NUMBER NOT NULL,

    CONSTRAINT fk_commande_matiere
        FOREIGN KEY (id_matiere)
        REFERENCES Matiere_premiere(id_matiere),

    CONSTRAINT fk_commande_fournisseur
        FOREIGN KEY (id_fournisseur)
        REFERENCES Fournisseur(id_fournisseur)
);

-- 5. LOT
CREATE TABLE Lot (
    id_lot NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_lot VARCHAR2(100) NOT NULL UNIQUE,
    capacite NUMBER(10,2) NOT NULL,
    id_matiere NUMBER NOT NULL,

    CONSTRAINT fk_lot_matiere
        FOREIGN KEY (id_matiere)
        REFERENCES Matiere_premiere(id_matiere)
);

-- 6. MOUVEMENT STOCK
CREATE TABLE Mouvement_stock (
    id_mouvement NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_mouvement VARCHAR2(50) NOT NULL,
    date_mouvement TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id_utilisateur NUMBER NOT NULL,
    id_matiere NUMBER NOT NULL,
    id_lot NUMBER NOT NULL,

    CONSTRAINT fk_mouvement_utilisateur
        FOREIGN KEY (id_utilisateur)
        REFERENCES Utilisateur(id_utilisateur),

    CONSTRAINT fk_mouvement_matiere
        FOREIGN KEY (id_matiere)
        REFERENCES Matiere_premiere(id_matiere),

    CONSTRAINT fk_mouvement_lot
        FOREIGN KEY (id_lot)
        REFERENCES Lot(id_lot)
);

-- 7. PRODUIT PHARMACEUTIQUE
CREATE TABLE Produit_pharmaceutiques (
    id_produit NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_produit VARCHAR2(150) NOT NULL,
    type_produit VARCHAR2(100)
);

-- 8. PRODUCTION
CREATE TABLE Production (
    id_production NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produit NUMBER NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE,
    statut VARCHAR2(50),

    CONSTRAINT fk_production_produit
        FOREIGN KEY (id_produit)
        REFERENCES Produit_pharmaceutiques(id_produit)
);

-- ==========================================
-- INDEXES
-- ==========================================

CREATE INDEX idx_commande_matiere
ON Commande_Fournisseur(id_matiere);

CREATE INDEX idx_commande_fournisseur
ON Commande_Fournisseur(id_fournisseur);

CREATE INDEX idx_mouvement_utilisateur
ON Mouvement_stock(id_utilisateur);

CREATE INDEX idx_mouvement_matiere
ON Mouvement_stock(id_matiere);

CREATE INDEX idx_mouvement_lot
ON Mouvement_stock(id_lot);

CREATE INDEX idx_production_produit
ON Production(id_produit);
